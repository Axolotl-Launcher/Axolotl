use crate::{
    LauncherInfo, Snapshot,
    http::gate,
    protocol::Handler,
    session::{Inner, Shared},
};
use axum::{Router, middleware};
use rmcp::transport::{
    StreamableHttpServerConfig,
    streamable_http_server::{
        session::local::LocalSessionManager, tower::StreamableHttpService,
    },
};
use std::{
    sync::{Arc, Mutex},
    time::Duration,
};
use tokio::{net::TcpListener, sync::Semaphore, task::JoinHandle};
use tokio_util::sync::CancellationToken;
pub struct Server {
    pub(crate) shared: Arc<Shared>,
    task: Option<JoinHandle<()>>,
}

impl Server {
    /// The token must be generated by the launcher and never sent in a URL.
    pub async fn start(
        port: u16,
        token: String,
        full_access: bool,
        require_auth: bool,
        info: LauncherInfo,
        changed: impl Fn(Snapshot) + Send + Sync + 'static,
    ) -> std::io::Result<Self> {
        let listener =
            TcpListener::bind((std::net::Ipv4Addr::LOCALHOST, port)).await?;
        let port = listener.local_addr()?.port();
        let mut sessions = LocalSessionManager::default();
        sessions.session_config.init_timeout = Some(Duration::from_secs(60));
        sessions.session_config.keep_alive = Some(Duration::from_secs(90));
        let shared = Arc::new(Shared {
            inner: Mutex::new(Inner {
                snapshot: Snapshot {
                    running: true,
                    full_access,
                    require_auth,
                    endpoint: Some(format!("http://127.0.0.1:{port}/mcp")),
                    ..Default::default()
                },
                slots: Default::default(),
                active: None,
            }),
            changed: Arc::new(changed),
            sessions: Arc::new(sessions),
            token,
            info,
            shutdown: CancellationToken::new(),
            admission: Semaphore::new(1),
        });
        let factory = shared.clone();
        let transport = StreamableHttpService::new(
            move || {
                Ok(Handler {
                    shared: factory.clone(),
                    id: Mutex::new(None),
                })
            },
            shared.sessions.clone(),
            StreamableHttpServerConfig::default()
                .with_cancellation_token(shared.shutdown.clone())
                .with_json_response(true)
                .with_max_request_body_bytes(16 * 1024)
                .enforce_origin_validation(),
        );
        let app = Router::new()
            .nest_service("/mcp", transport)
            .layer(middleware::from_fn_with_state(shared.clone(), gate));
        let shutdown = shared.shutdown.clone();
        let task = tokio::spawn(async move {
            if let Err(error) = axum::serve(listener, app)
                .with_graceful_shutdown(shutdown.cancelled_owned())
                .await
            {
                tracing::warn!(%error, "MCP listener failed");
            }
        });
        Ok(Self {
            shared,
            task: Some(task),
        })
    }

    pub fn snapshot(&self) -> Snapshot {
        self.shared
            .inner
            .lock()
            .unwrap_or_else(|e| e.into_inner())
            .snapshot
            .clone()
    }

    pub fn approve(&self, id: &str) -> bool {
        self.shared.update(|inner| {
            inner
                .slots
                .get_mut(id)
                .filter(|slot| slot.connection.awaiting_approval)
                .and_then(|slot| {
                    slot.connection.awaiting_approval = false;
                    slot.approval.take()
                })
                .is_some_and(|approval| approval.send(true).is_ok())
        })
    }

    pub fn deny(&self, id: &str) {
        self.shared.update(|inner| {
            if let Some(slot) = inner.slots.get_mut(id) {
                if slot.connection.awaiting_approval {
                    if let Some(approval) = slot.approval.take() {
                        let _ = approval.send(false);
                    }
                }
            }
        });
    }

    pub async fn disconnect(&self, id: &str) {
        self.shared.disconnect(id).await;
    }

    pub async fn stop(mut self) {
        self.shared.update(|inner| {
            for (_, slot) in inner.slots.drain() {
                slot.cancel.cancel();
            }
            inner.active = None;
        });
        self.shared.shutdown.cancel();
        self.shared.update(|inner| {
            inner.snapshot.running = false;
            inner.snapshot.endpoint = None;
        });
        if let Some(mut task) = self.task.take() {
            if tokio::time::timeout(Duration::from_secs(2), &mut task)
                .await
                .is_err()
            {
                task.abort();
            }
        }
    }
}

impl Drop for Server {
    fn drop(&mut self) {
        self.shared.shutdown.cancel();
        if let Some(task) = self.task.take() {
            task.abort();
        }
    }
}
