// Level backfill of the 28 governed resident tasks (spec §5.6): every item has
// a level and a basis, and the lock predicate holds — a task holding a §8.1
// business lock or the single-writer permit is L3 (L0 members excepted, their
// shared accesses are separated in phase 3).
//
// Usage: node scripts/axolotl/sched-level-predicate-check.mjs [--dir <inventory dir>] [--write]
// --write also renders .agents/plans/sched-level-predicate-report.md and
// .agents/plans/sched-governance-table.md from the policy.

import { existsSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { defaultOutDir, isMain, loadPolicy, outputPaths, parseArgs, readJson, repoRoot } from './sched-utils.mjs'

export const LEVELS = ['L0', 'L1', 'L2', 'L3', 'L4']
/** §8.1 business locks and the single-writer permit: holding one makes a task L3. */
export const PREDICATE_RESOURCES = [
    'theseus::api::instance::backup::INSTANCE_MAINTENANCE_LOCKS',
    'theseus::state::InstanceLockManager.locks',
    'theseus::state::State.install_admission_locks',
    'theseus::state::State.install_db_semaphore',
    'theseus::state::State.install_execution_locks',
]

export function expectedGovernanceIds(policy) {
    const resident = Array.from({ length: 30 }, (_, index) => `R${index + 1}`).filter((id) => !(id in policy.governanceRemoved))
    return [...resident, 'ACCENT']
}

export function checkGovernance(policy, inventory) {
    const failures = []
    const generated = new Set(inventory.items.map((item) => item.ident))
    const ids = policy.governance.map((entry) => entry.id)
    const expected = expectedGovernanceIds(policy)
    for (const id of expected) if (!ids.includes(id)) failures.push(`${id} has no governance entry`)
    for (const id of ids) if (!expected.includes(id)) failures.push(`${id} is not a governed item`)
    for (const entry of policy.governance) {
        if (!LEVELS.includes(entry.level)) failures.push(`${entry.id}: level ${entry.level} is not one of ${LEVELS.join('/')}`)
        if (!entry.basis?.trim()) failures.push(`${entry.id}: no basis`)
        if (!existsSync(path.resolve(repoRoot, entry.file))) failures.push(`${entry.id}: ${entry.file} does not exist`)
        for (const ident of entry.locks) if (!generated.has(ident)) failures.push(`${entry.id}: lock ${ident} is not in the inventory`)
        const predicate = entry.locks.some((ident) => PREDICATE_RESOURCES.includes(ident))
        if (predicate && !['L3', 'L0'].includes(entry.level)) failures.push(`${entry.id}: holds a predicate lock but is ${entry.level}, not L3`)
    }
    const telemetry = policy.governance.find((entry) => entry.id === 'R3')
    if (!telemetry?.limitation?.startsWith('partial fix + declared limitation')) failures.push('R3 must stay recorded as a partial fix with a declared limitation')
    const accent = policy.governance.find((entry) => entry.id === 'ACCENT')
    if (accent && !(accent.level === 'L2' && accent.signal && accent.boundedExit)) failures.push('ACCENT must be L2, signal-driven, with a bounded exit')
    return failures
}

function renderReport(policy) {
    const done = policy.governance.filter((entry) => entry.backfilled)
    const kept = policy.governance.filter((entry) => !entry.backfilled)
    const row = (entry) => `| ${entry.id} | \`${entry.file}\` | ${entry.business} | ${entry.level}${entry.backfilled ? '' : ' (conservative)'} | ${entry.locks.map((ident) => `\`${ident}\``).join('<br>') || '—'} | ${entry.basis}${entry.limitation ? `<br>**${entry.limitation}**` : ''} |`
    return [
        '# Scheduler level-predicate backfill (T0.5)',
        '',
        `Generated by \`node scripts/axolotl/sched-level-predicate-check.mjs --write\` from \`scripts/axolotl/sched-policy.json\`.`,
        '',
        `- Backfilled: **${done.length}** rows. Not backfilled: **${kept.length}** rows, each kept at the stricter level and marked "conservative".`,
        '- Predicate: holding a §8.1 business lock or the single-writer permit `install_db_semaphore` makes a task L3; throttling semaphores do not count.',
        '- R3 (telemetry) is a partial fix with a declared limitation, not a fix: see spec §5.6 and §11.2 item 13.',
        '',
        '| ID | File | Business | Level | Locks held | Basis |',
        '| --- | --- | --- | --- | --- | --- |',
        ...policy.governance.map(row),
        '',
    ].join('\n')
}

function renderGovernance(policy) {
    return [
        '# Scheduler governance table',
        '',
        'Shared by T0.5, T0.10 and T3.4. Generated from `scripts/axolotl/sched-policy.json` (`governance`).',
        '',
        '| ID | Business | Level | Signal-driven | Bounded exit |',
        '| --- | --- | --- | --- | --- |',
        ...policy.governance.map((entry) => `| ${entry.id} | ${entry.business} | ${entry.level} | ${entry.signal ? 'yes' : '—'} | ${entry.boundedExit ? 'yes' : '—'} |`),
        '',
        `Removed from the t12 list: ${Object.entries(policy.governanceRemoved).map(([id, reason]) => `${id} (${reason})`).join('; ')}.`,
        '',
    ].join('\n')
}

if (isMain(import.meta.url)) {
    const args = parseArgs(process.argv.slice(2))
    const policy = loadPolicy()
    const failures = checkGovernance(policy, readJson(outputPaths(args.dir ?? defaultOutDir).inventory))
    const kept = policy.governance.filter((entry) => !entry.backfilled).length
    console.log(`governed items: ${policy.governance.length}; backfilled ${policy.governance.length - kept}, not backfilled ${kept}`)
    if (args.write) {
        writeFileSync(path.resolve(repoRoot, '.agents/plans/sched-level-predicate-report.md'), renderReport(policy))
        writeFileSync(path.resolve(repoRoot, '.agents/plans/sched-governance-table.md'), renderGovernance(policy))
    }
    if (failures.length > 0) {
        for (const failure of failures) console.error(failure)
        process.exit(1)
    }
}
