import assert from 'node:assert/strict'
import { spawnSync } from 'node:child_process'
import fs from 'node:fs/promises'
import os from 'node:os'
import path from 'node:path'
import test from 'node:test'
import { fileURLToPath } from 'node:url'

const script = fileURLToPath(new URL('./set-version.mjs', import.meta.url))

async function fixture(t) {
    const directory = await fs.mkdtemp(path.join(os.tmpdir(), 'axolotl-set-version-test-'))
    t.after(async () => {
        assert.equal(path.dirname(directory), path.resolve(os.tmpdir()))
        assert.ok(path.basename(directory).startsWith('axolotl-set-version-test-'))
        await fs.rm(directory, { recursive: true, force: true })
    })
    const files = {
        'apps/app-frontend/package.json': '{"name":"frontend","version":"0.1.0"}\n',
        'Cargo.toml': '[workspace]\nmembers = ["apps/app", "packages/app-lib"]\nresolver = "2"\n',
        'apps/app/Cargo.toml':
            '[package]\nname = "theseus_gui"\nversion = "0.1.0"\nedition = "2024"\n\n[dependencies]\ntheseus = { path = "../../packages/app-lib" }\n',
        'packages/app-lib/Cargo.toml':
            '[package]\nname = "theseus"\nversion = "0.1.0"\nedition = "2024"\n',
        'apps/app/src/lib.rs': '',
        'packages/app-lib/src/lib.rs': '',
        'Cargo.lock':
            '# This file is automatically @generated by Cargo.\n# It is not intended for manual editing.\nversion = 4\n\n[[package]]\nname = "theseus"\nversion = "0.1.0"\n\n[[package]]\nname = "theseus_gui"\nversion = "0.1.0"\ndependencies = [\n "theseus",\n]\n',
    }
    for (const [filename, content] of Object.entries(files)) {
        const destination = path.join(directory, filename)
        await fs.mkdir(path.dirname(destination), { recursive: true })
        await fs.writeFile(destination, content)
    }
    const run = (tag) =>
        spawnSync(process.execPath, [script, tag], {
            cwd: directory,
            env: { ...process.env, CARGO_NET_OFFLINE: 'true' },
            encoding: 'utf8',
            timeout: 30000,
        })
    return { directory, files, run }
}

for (const tag of ['v2.3.4-beta.1', '2.3.4']) {
    test(`${tag} keeps manifests and the lockfile valid for locked release resolution`, async (t) => {
        const { directory, run } = await fixture(t)
        const version = tag.replace(/^v/, '')
        const result = run(tag)
        assert.equal(result.status, 0, result.stderr)
        const frontend = JSON.parse(
            await fs.readFile(path.join(directory, 'apps/app-frontend/package.json'), 'utf8'),
        )
        assert.equal(frontend.version, version)
        const lockfile = await fs.readFile(path.join(directory, 'Cargo.lock'), 'utf8')
        const metadata = spawnSync(
            'cargo',
            ['metadata', '--locked', '--offline', '--format-version', '1'],
            { cwd: directory, encoding: 'utf8', timeout: 30000 },
        )
        assert.equal(metadata.status, 0, metadata.stderr)
        const packages = JSON.parse(metadata.stdout).packages
        assert.deepEqual(
            packages.map(({ name, version }) => ({ name, version })),
            [
                { name: 'theseus', version },
                { name: 'theseus_gui', version },
            ],
        )
        assert.equal(await fs.readFile(path.join(directory, 'Cargo.lock'), 'utf8'), lockfile)
        const repeated = run(tag)
        assert.equal(repeated.status, 0, repeated.stderr)
        assert.equal(await fs.readFile(path.join(directory, 'Cargo.lock'), 'utf8'), lockfile)
    })
}

test('invalid tags fail before changing manifests or the lockfile', async (t) => {
    const { directory, files, run } = await fixture(t)
    const result = run('invalid-tag')
    assert.notEqual(result.status, 0)
    assert.match(result.stderr, /Expected a semantic version tag/)
    for (const [filename, content] of Object.entries(files)) {
        assert.equal(await fs.readFile(path.join(directory, filename), 'utf8'), content)
    }
})

test('repairs a stale lockfile even when manifest versions already match the tag', async (t) => {
    const { directory, files, run } = await fixture(t)
    const filename = path.join(directory, 'Cargo.lock')
    const staleLockfile = files['Cargo.lock'].replaceAll('"0.1.0"', '"0.0.9"')
    await fs.writeFile(filename, staleLockfile)
    const result = run('v0.1.0')
    assert.equal(result.status, 0, result.stderr)
    assert.equal(await fs.readFile(filename, 'utf8'), files['Cargo.lock'])
})
